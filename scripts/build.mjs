import {readFile,writeFile,mkdir,rm,copyFile} from 'node:fs/promises';
import path from 'node:path';
import {loadStaticAssets} from './static-assets.mjs';
const root=path.resolve('.'), output=path.resolve(root,'dist');
if(path.relative(root,output)!=='dist')throw new Error('Unexpected build directory');
await rm(output,{recursive:true,force:true});await mkdir(path.join(output,'server'),{recursive:true});await mkdir(path.join(output,'.openai'),{recursive:true});
const {assets,version}=await loadStaticAssets();
const api=await readFile('server/api.js','utf8');
const serving=await readFile('server/static.js','utf8');
const worker=`${api}\n${serving}\nconst ASSETS=${JSON.stringify(assets)};\nexport const ASSET_VERSION=${JSON.stringify(version)};\nconst IDS=new Set(Array.from({length:90},(_,i)=>'m'+String(i+1).padStart(2,'0')));\nexport default {async fetch(request,env){const url=new URL(request.url);if(url.pathname==='/api/progress')return progressAPI(request,env,IDS);return staticAsset(request,url,ASSETS,ASSET_VERSION);}};\n`;
await writeFile(path.join(output,'server/index.js'),worker);await copyFile('.openai/hosting.json',path.join(output,'.openai/hosting.json'));
console.log('Built Robótica Java: Worker, assets and progress API.');
